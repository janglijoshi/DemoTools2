"""Generates src/extras.gen.h: stickers, charms and agents for the DemoTools2 menu.

usage: python3 tools/gen_extras.py <skinstudio_catalog.json> [items_game.txt]
The catalog gives names; items_game.txt (CS2's own item file, optional) confirms agent model paths.
"""
import json, re, sys

cat = json.load(open(sys.argv[1], encoding="utf-8"))
models = None
if len(sys.argv) > 2:
    t = open(sys.argv[2], encoding="utf-8", errors="replace").read()
    models = set(re.findall(r'"model_player"\s*"(agents/models/[^"]+\.vmdl)"', t))

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')

out = ["// GENERATED by tools/gen_extras.py - do not edit.", "#pragma once", "#include <cstdint>", "",
       "struct CatSticker { uint32_t id; const char* name; uint8_t rarity; };",
       "struct CatCharm { uint32_t id; const char* name; uint8_t rarity; };",
       "struct CatAgent { const char* model; const char* name; uint8_t team; uint8_t rarity; };", ""]
st = sorted(cat["stickers"], key=lambda s: s["name"].lower())
out.append("inline constexpr CatSticker kStickers[] = {")
out += ['    {%d, "%s", %d},' % (s["id"], esc(s["name"].replace("Sticker | ", "")), s.get("r", 1)) for s in st]
out += ["};", "inline constexpr int kNumStickers = %d;" % len(st), ""]
ch = sorted(cat["charms"], key=lambda s: s["name"].lower())
out.append("inline constexpr CatCharm kCharms[] = {")
out += ['    {%d, "%s", %d},' % (c["id"], esc(c["name"].replace("Charm | ", "")), c.get("r", 1)) for c in ch]
out += ["};", "inline constexpr int kNumCharms = %d;" % len(ch), ""]
ag = []
for a in cat["agents"]:
    if not a.get("model") or a["model"] == "null":
        continue
    path = "agents/models/%s.vmdl" % a["model"]
    if models is not None and path not in models:
        print("skipping agent not in items_game:", path)
        continue
    ag.append((path, a["name"], a["team"], a.get("r", 1)))
ag.sort(key=lambda x: (x[2], x[1].lower()))
out.append("inline constexpr CatAgent kAgents[] = {")
out += ['    {"%s", "%s", %d, %d},' % (p, esc(n), tm, r) for p, n, tm, r in ag]
out += ["};", "inline constexpr int kNumAgents = %d;" % len(ag), ""]
open("src/extras.gen.h", "w", encoding="utf-8").write("\n".join(out))
print("stickers %d, charms %d, agents %d" % (len(st), len(ch), len(ag)))
