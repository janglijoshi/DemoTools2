"""Writes src/catalog.gen.h (guns, knives, gloves and their finishes) from SkinStudio's item catalog.

    python3 tools/gen_catalog.py <skinstudio_catalog.json> [<skins_en.json with legacy_model flags>]

legacy_model comes from the game's items_game.txt (use_legacy_model): such finishes are painted for the weapon's
legacy mesh, and the weapon must switch to that mesh or the texture lands scrambled.
"""
import json, pathlib, sys

src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "../SkinStudio/plugin/SkinStudio/catalog/skinstudio_catalog.json")
d = json.loads(src.read_text(encoding="utf-8"))
legacy = set()
if len(sys.argv) > 2:
    for x in json.loads(pathlib.Path(sys.argv[2]).read_text(encoding="utf-8")):
        if x.get("legacy_model"):
            legacy.add((int(x["weapon_defindex"]), int(x["paint"])))
CATS = ["pistols", "rifles", "snipers", "smgs", "heavy", "knives", "gloves"]

def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

weapons = [w for w in d["weapons"] if w["cat"] in CATS]
weapons.sort(key=lambda w: (CATS.index(w["cat"]), w["name"]))
defs = {w["def"] for w in weapons}
skins = [s for s in d["skins"] if s["def"] in defs and s["paint"] > 0]
skins.sort(key=lambda s: (s["def"], -s["r"], s["name"]))

out = ["// GENERATED by tools/gen_catalog.py - do not edit.", "#pragma once", "#include <cstdint>", "",
       "struct CatWeapon { uint16_t def; const char* cls; const char* name; uint8_t cat; };",
       "struct CatSkin { uint16_t def; uint16_t paint; const char* name; uint8_t rarity; float minWear, maxWear; uint8_t legacy; };", "",
       "static const char* const kCategories[] = {" + ", ".join(c(x.capitalize() if x != "smgs" else "SMGs") for x in CATS) + "};",
       f"static const int kNumCategories = {len(CATS)};", "",
       "static const CatWeapon kWeapons[] = {"]
for w in weapons:
    out.append(f"    {{{w['def']}, {c(w['cls'])}, {c(w['name'])}, {CATS.index(w['cat'])}}},")
out += ["};", f"static const int kNumWeapons = {len(weapons)};", "", "static const CatSkin kSkins[] = {"]
for s in skins:
    out.append(f"    {{{s['def']}, {s['paint']}, {c(s['name'])}, {s['r']}, {float(s['min']):.2f}f, {float(s['max']):.2f}f, {1 if (s['def'], s['paint']) in legacy else 0}}},")
out += ["};", f"static const int kNumSkins = {len(skins)};", ""]
pathlib.Path(__file__).resolve().parents[1].joinpath("src/catalog.gen.h").write_text("\n".join(out), encoding="utf-8")
print(len(weapons), "weapons,", len(skins), "finishes,", sum(1 for x in skins if (x['def'], x['paint']) in legacy), "legacy")
